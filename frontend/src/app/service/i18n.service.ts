@Injectable({ providedIn: 'root' })
export class I18nService {
  private fallbackLanguage = 'en';
  private languageSubject = new BehaviorSubject<string>(localStorage.getItem('tedbus-language') || this.fallbackLanguage);
  language$ = this.languageSubject.asObservable();

  get language(): string {
    return this.languageSubject.value;
  }

  setLanguage(language: string): void {
    const nextLanguage = translations[language] ? language : this.fallbackLanguage;
    localStorage.setItem('tedbus-language', nextLanguage);
    document.documentElement.lang = nextLanguage;
    this.languageSubject.next(nextLanguage);
  }

  translate(key: string): string {
    return translations[this.language]?.[key] || translations[this.fallbackLanguage][key] || key;
  }
} 